import { z } from "zod";

/**
 * §18 — the font library. Every family here is SIL Open Font Licence via
 * Google Fonts, so it can ship in commercial exports. Premium/licensed
 * families get added with `source: "licensed"` and a licence reference.
 */
export const FontRole = z.enum(["headline", "support", "accent"]);
export type FontRole = z.infer<typeof FontRole>;

export const FontFamilyMeta = z.object({
  family: z.string(),
  googleFamily: z.string().optional(),
  source: z.enum(["google", "local", "licensed"]).default("google"),
  licence: z.string().default("OFL-1.1"),
  category: z.enum(["sans", "serif", "display", "mono", "script"]),
  width: z.enum(["condensed", "normal", "wide"]).default("normal"),
  /** §18 "personality" — feeds the planner's font choice. */
  personality: z.array(z.string()).default([]),
  roles: z.array(FontRole).min(1),
  weights: z.array(z.number().int()).min(1),
  italics: z.boolean().default(false),
  pairsWith: z.array(z.string()).default([]),
  languages: z.array(z.string()).default(["latin"]),
  /** Optical correction: caps-heavy display faces need tighter default tracking. */
  defaultTracking: z.number().default(0),
});
export type FontFamilyMeta = z.infer<typeof FontFamilyMeta>;

