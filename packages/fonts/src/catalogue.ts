export const CATALOGUE_BY_FAMILY = new Map(FONT_CATALOGUE.map((f) => [f.family, f]));

export function familiesForRole(role: FontRole): FontFamilyMeta[] {
  return FONT_CATALOGUE.filter((f) => f.roles.includes(role));
}

/** Condensed one-line descriptions for the planner prompt — keeps tokens low (§32). */
export function catalogueDigest(): string {
  return FONT_CATALOGUE.map(
    (f) =>
      `${f.family} — ${f.category}/${f.width}; ${f.personality.join(", ")}; roles: ${f.roles.join("/")}; weights: ${f.weights.join(",")}`,
  ).join("\n");
}
